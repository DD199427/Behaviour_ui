"""Turn pending flags into a Neo4j-ready relationship CSV + Cypher, in the same shape as
neo4j-behaviour-export/build_behaviour_map.py so the graph team loads it the same way.

Writes into the SAME export folder the teammate already has (neo4j_export/s1/), as new files:
  flagged_behaviours.csv         one row per flag: (:Entity)-[:FLAGGED_AS]->(:BehaviourLabel)
  load_flagged_behaviours.cypher MERGEs the label nodes and relationships; safe to re-run

Node labels / ID properties must match what the teammate used to load the vectors
(see neo4j-behaviour-export/templates/load_neo4j.py --account-label etc.); change the
*_LABEL / *_ID_PROP constants below if his graph uses different ones.
"""
import json
from datetime import date, datetime, timezone
from pathlib import Path

import pandas as pd

from lib.data import EXPORT_DIR
from lib.store import label_status, load_flags, load_labels, mark_exported

ACCOUNT_LABEL, ACCOUNT_ID_PROP = "Account", "account_id"
MERCHANT_LABEL, MERCHANT_NAME_PROP, MERCHANT_CATEGORY_PROP = "Merchant", "name", "category"
TXN_LABEL, TXN_ID_PROP = "Transaction", "txn_id"
ENTITY_LABEL = {"account": ACCOUNT_LABEL, "merchant": MERCHANT_LABEL, "transaction": TXN_LABEL}
COLUMNS = ["rel_type", "source_label", "source_id", "source_category", "target_label", "target_id",
           "target_category", "score", "rank", "schema", "version", "asof", "properties_json",
           "target_properties_json"]

CYPHER = """// Flagged behaviours, export batch {batch} ({n} flags), generated by the Behaviour UI.
// Loads flagged_behaviours.csv: copy it into the Neo4j import folder, then run with cypher-shell
// (in Neo4j Browser put :auto in front of the LOAD CSV). Needs Neo4j 5.x; no APOC or GDS.
// Accounts / merchants / transactions must already exist (matched by ID, same as the vector export);
// BehaviourLabel nodes are created. Re-running is safe: MERGE does not duplicate anything.

CREATE CONSTRAINT bb_label_name IF NOT EXISTS FOR (b:BehaviourLabel) REQUIRE b.name IS UNIQUE;

LOAD CSV WITH HEADERS FROM 'file:///flagged_behaviours.csv' AS row
CALL {{
  WITH row
  MERGE (b:BehaviourLabel {{name: row.target_id}})
  SET b.properties_json = row.target_properties_json, b.schema = row.schema, b.version = row.version
}} IN TRANSACTIONS OF 1000 ROWS;

LOAD CSV WITH HEADERS FROM 'file:///flagged_behaviours.csv' AS row
WITH row WHERE row.source_label = '{account_label}'
CALL {{
  WITH row
  MATCH (a:{account_label} {{{account_id}: row.source_id}})
  MATCH (b:BehaviourLabel {{name: row.target_id}})
  MERGE (a)-[r:FLAGGED_AS]->(b)
  SET r.confidence = toFloat(row.score), r.properties_json = row.properties_json
}} IN TRANSACTIONS OF 1000 ROWS;

LOAD CSV WITH HEADERS FROM 'file:///flagged_behaviours.csv' AS row
WITH row WHERE row.source_label = '{merchant_label}'
CALL {{
  WITH row
  MATCH (m:{merchant_label} {{{merchant_name}: row.source_id, {merchant_category}: row.source_category}})
  MATCH (b:BehaviourLabel {{name: row.target_id}})
  MERGE (m)-[r:FLAGGED_AS]->(b)
  SET r.confidence = toFloat(row.score), r.properties_json = row.properties_json
}} IN TRANSACTIONS OF 1000 ROWS;

LOAD CSV WITH HEADERS FROM 'file:///flagged_behaviours.csv' AS row
WITH row WHERE row.source_label = '{txn_label}'
CALL {{
  WITH row
  MATCH (t:{txn_label} {{{txn_id}: row.source_id}})
  MATCH (b:BehaviourLabel {{name: row.target_id}})
  MERGE (t)-[r:FLAGGED_AS]->(b)
  SET r.confidence = toFloat(row.score), r.properties_json = row.properties_json
}} IN TRANSACTIONS OF 1000 ROWS;

// Checks
MATCH (b:BehaviourLabel) RETURN b.name, count {{ (b)<-[:FLAGGED_AS]-() }} AS flags ORDER BY flags DESC;
"""


def all_pending_flags():
    """Every flag not yet exported, regardless of whether its behaviour is confirmed."""
    flags = load_flags()
    return flags[~flags["exported"]] if not flags.empty else flags


def pending_flags(include_candidates=False):
    """Flags ready to export: known fraud types and active (corroborated) custom behaviours.
    Candidate (unconfirmed) behaviours are held back unless include_candidates=True."""
    pending = all_pending_flags()
    if pending.empty or include_candidates:
        return pending
    return pending[pending["label"].map(lambda l: label_status(l) != "candidate")]


def build_export(flags_df=None):
    """Writes flagged_behaviours.csv + load_flagged_behaviours.cypher for the given flags
    (default: every flag not yet exported) and marks them exported. Returns a summary dict."""
    flags_df = pending_flags() if flags_df is None else flags_df
    if flags_df.empty:
        return {"rows": 0}

    labels = load_labels()
    batch = datetime.now(timezone.utc).strftime("v%Y%m%dT%H%M%S")
    rows = []
    for _, f in flags_df.iterrows():
        label_meta = labels.get(f["label"], {})
        props = {"ts": f["ts"], "user": f["user"], "note": f["note"], "is_new_label": bool(f["is_new_label"]),
                 "batch": batch}
        target_props = {"description": label_meta.get("description", ""), "status": label_meta.get("status", ""),
                        "created_at": label_meta.get("created_at", ""), "created_by": label_meta.get("created_by", "")}
        rows.append(["FLAGGED_AS", ENTITY_LABEL[f["entity_type"]], f["entity_id"], f["entity_category"],
                     "BehaviourLabel", f["label"], "", f["confidence"], "", "labels", batch,
                     date.today().isoformat(), json.dumps(props, sort_keys=True), json.dumps(target_props, sort_keys=True)])

    out_csv = EXPORT_DIR / "flagged_behaviours.csv"
    existing = pd.read_csv(out_csv) if out_csv.exists() else pd.DataFrame(columns=COLUMNS)
    pd.concat([existing, pd.DataFrame(rows, columns=COLUMNS)], ignore_index=True).to_csv(out_csv, index=False)

    out_cypher = EXPORT_DIR / "load_flagged_behaviours.cypher"
    out_cypher.write_text(CYPHER.format(
        batch=batch, n=len(rows), account_label=ACCOUNT_LABEL, account_id=ACCOUNT_ID_PROP,
        merchant_label=MERCHANT_LABEL, merchant_name=MERCHANT_NAME_PROP, merchant_category=MERCHANT_CATEGORY_PROP,
        txn_label=TXN_LABEL, txn_id=TXN_ID_PROP))

    mark_exported(flags_df["flag_id"].tolist(), batch)
    return {"rows": len(rows), "batch": batch, "csv": str(out_csv), "cypher": str(out_cypher)}
